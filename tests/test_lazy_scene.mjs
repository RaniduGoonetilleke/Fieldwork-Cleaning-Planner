import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';

const source=fs.readFileSync(new URL('../public/team.js',import.meta.url),'utf8');
const html=fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf8');
const extract=name=>source.slice(source.indexOf('function '+name+'('),source.indexOf('\nfunction ',source.indexOf('function '+name+'(')+1));
const nodes=new Map();
const node=id=>{if(!nodes.has(id))nodes.set(id,{hidden:id==='team-stage',setAttribute(){},removeAttribute(){},querySelector(){return {focus(){}}},scrollIntoView(){}});return nodes.get(id);};
let started=0,resized=0;
const state={job:'G1',forceValid:true,data:null,pending:false,scene:null};
const context={state,$:node,document:{querySelector:node},renderTeam(){},initScene(){started++;},requestAnimationFrame:f=>f(),setTimeout:f=>f()};
vm.createContext(context);
vm.runInContext(extract('showStep')+'\n'+extract('toggleScene'),context);
context.showStep(2,false);
assert.equal(started,0,'Opening Team must not initialize WebGL.');
assert.equal(node('team-stage').hidden,true);
assert.match(html,/<button[^>]+id="guide-show-3d"[^>]+aria-expanded="false"/);
assert.match(html,/<div id="team-stage"[^>]+hidden>/);
context.toggleScene();
assert.equal(started,1,'Only the explicit Show 3D action initializes the scene.');
assert.equal(node('team-stage').hidden,false);
context.toggleScene();
assert.equal(started,1,'Hiding the optional scene must not initialize it.');
state.scene={resize(){resized++;}};
context.toggleScene();
assert.equal(started,1,'Showing an existing scene reuses it.');
assert.equal(resized,1);
console.log('The team workflow stays usable without initializing the optional 3D scene.');
